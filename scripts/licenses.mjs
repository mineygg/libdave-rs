// Generates THIRD_PARTY_LICENSES for everything linked into the native addon and
// copies it, with LICENSE, into each package that gets published.
//
//   node scripts/licenses.mjs           write the files
//   node scripts/licenses.mjs --check   fail if any file is missing or stale
//
// Needs the git submodules and `cargo`, but compiles nothing.
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const check = process.argv.includes('--check');
const read = (path) =>
  readFileSync(resolve(root, path), 'utf8').replace(/\r\n/g, '\n');

const metadata = JSON.parse(
  execFileSync('cargo', ['metadata', '--format-version', '1', '--locked'], {
    cwd: root,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  }),
);
const packages = new Map(metadata.packages.map((p) => [p.id, p]));
const nodes = new Map(metadata.resolve.nodes.map((n) => [n.id, n]));

// Normal dependencies of the addon on any platform. Build scripts and
// procedural macros run at compile time and are not linked into it.
const start = metadata.packages.find((p) => p.name === 'libdave-node').id;
const linked = new Set();
const queue = [start];
while (queue.length > 0) {
  for (const dep of nodes.get(queue.pop()).deps) {
    const isProcMacro = packages
      .get(dep.pkg)
      .targets.some((t) => t.kind.includes('proc-macro'));
    if (
      linked.has(dep.pkg) ||
      isProcMacro ||
      !dep.dep_kinds.some((k) => k.kind === null)
    ) {
      continue;
    }
    linked.add(dep.pkg);
    queue.push(dep.pkg);
  }
}

const sections = [];
const add = (title, note, text) =>
  sections.push(
    `${'='.repeat(78)}\n${title}\n${note}\n${'='.repeat(78)}\n\n${text.trim()}\n`,
  );

const vendor = 'crates/libdave-sys/vendor';
add(
  'libdave (Discord)',
  'MIT. https://github.com/discord/libdave',
  read(`${vendor}/libdave/LICENSE`),
);
add(
  'mlspp (Cisco Systems)',
  'BSD-2-Clause. https://github.com/cisco/mlspp',
  read(`${vendor}/mlspp/LICENSE`),
);
add(
  'variant (Michael Park), bundled with mlspp',
  'BSL-1.0. Copyright Michael Park, 2015-2017',
  read('licenses/BSL-1.0.txt'),
);
add(
  'JSON for Modern C++ (nlohmann/json)',
  'MIT. https://github.com/nlohmann/json',
  read(`${vendor}/nlohmann_json/LICENSE.MIT`),
);
add(
  'Code embedded in nlohmann/json',
  [
    'UTF-8 decoder: Copyright 2008-2009 Bjoern Hoehrmann (MIT)',
    'Grisu2: Copyright 2009 Florian Loitsch (MIT)',
    'Hedley: Evan Nemerson (CC0-1.0)',
    'Portions: Copyright 2018 The Abseil Authors (Apache-2.0, text below)',
  ].join('\n'),
  [
    read(`${vendor}/nlohmann_json/LICENSES/MIT.txt`),
    read(`${vendor}/nlohmann_json/LICENSES/CC0-1.0.txt`),
  ].join('\n\n'),
);
add(
  'Apache License 2.0',
  'Applies to OpenSSL, the Abseil portions above and crates marked Apache-2.0',
  read(`${vendor}/nlohmann_json/LICENSES/Apache-2.0.txt`),
);

const openssl = metadata.packages.find((p) => p.name === 'openssl-src');
const opensslDir = join(dirname(openssl.manifest_path), 'openssl');
add(
  `OpenSSL (openssl-src ${openssl.version}), statically linked`,
  'Apache-2.0. https://www.openssl.org',
  read(join(opensslDir, 'LICENSE.txt')),
);

add(
  'Rust standard library',
  'MIT OR Apache-2.0. https://github.com/rust-lang/rust',
  read('licenses/rust-std-MIT.txt'),
);

const crates = [...linked]
  .map((id) => packages.get(id))
  // This repository's own crates are covered by LICENSE.
  .filter((p) => p.source !== null)
  .sort((a, b) => a.name.localeCompare(b.name));
for (const crate of crates) {
  const dir = dirname(crate.manifest_path);
  const files = readdirSync(dir)
    .filter((f) => /^(license|copying|notice|unlicense)/i.test(f))
    .sort();
  let texts = files.map((f) => read(join(dir, f)));
  if (texts.length === 0 && crate.name.startsWith('napi')) {
    texts = [read('licenses/napi-rs.txt')];
  }
  if (texts.length === 0) {
    throw new Error(`no license text found for ${crate.name}`);
  }
  add(
    `${crate.name} ${crate.version} (Rust crate)`,
    `${crate.license}. ${crate.repository ?? ''}`.trim(),
    texts.map((t) => t.trim()).join(`\n\n${'-'.repeat(40)}\n\n`),
  );
}

const notices = `Third-party software included in @mineygg/libdave-rs and the libdave-sys crate.
Generated by scripts/licenses.mjs. Do not edit.

${sections.join('\n')}`;
const license = read('LICENSE');

const outputs = new Map([['THIRD_PARTY_LICENSES', notices]]);
outputs.set('crates/libdave-sys/THIRD_PARTY_LICENSES', notices);
outputs.set('crates/libdave-sys/LICENSE', license);
outputs.set('crates/libdave/LICENSE', license);

const platforms = readdirSync(join(root, 'npm')).sort();
for (const platform of platforms) {
  const dir = `npm/${platform}`;
  outputs.set(`${dir}/LICENSE`, license);
  outputs.set(`${dir}/THIRD_PARTY_LICENSES`, notices);

  const manifest = JSON.parse(read(`${dir}/package.json`));
  manifest.files = [
    `libdave.${platform}.node`,
    'LICENSE',
    'THIRD_PARTY_LICENSES',
  ];
  manifest.license = 'SEE LICENSE IN THIRD_PARTY_LICENSES';
  outputs.set(`${dir}/package.json`, `${JSON.stringify(manifest, null, 2)}\n`);
}

const stale = [];
for (const [path, content] of outputs) {
  const target = resolve(root, path);
  if (existsSync(target) && read(path) === content) continue;
  if (check) stale.push(path);
  else writeFileSync(target, content);
}
if (stale.length > 0) {
  console.error(
    `Run \`npm run licenses\`. Out of date:\n  ${stale.join('\n  ')}`,
  );
  process.exit(1);
}
console.log(
  `licenses ok: ${sections.length} sections, ${platforms.length} platform packages`,
);
